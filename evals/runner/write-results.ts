/**
 * Build the results table from the immutable official iterations and write it
 * into EVALUATION.md between <!-- results:start --> and <!-- results:end -->.
 *
 *   pnpm eval:results            # rewrite the block (and the trajectory files)
 *   pnpm eval:results --check    # exit 1 if the block is out of date
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

import { buildOptimizationTrajectory, readOptimizationTrajectory, writeOptimizationTrajectory } from "./trajectory";

const ROOT = resolve(import.meta.dirname, "../..");
const ITERATIONS = join(ROOT, "evals/iterations");
const DOC = join(ROOT, "EVALUATION.md");
const START = "<!-- results:start -->";
const END = "<!-- results:end -->";

type Metric = {
  runs: number;
  passed: number;
  passRate: number;
  criticalPassRate: number;
  firstPassValidRate: number;
  failedToolCalls: number;
  expectedGuardRejections: number;
  retries: number;
  meanTokensPerRun: number;
  meanWallTimeMs: number;
  meanTimeToVisibleSuccessMs: number | null;
};

function readJson<T>(path: string): T {
  return JSON.parse(readFileSync(path, "utf8")) as T;
}

const pct = (value: number) => `${(value * 100).toFixed(1)}%`;
const int = (value: number) => Math.round(value).toLocaleString("en-US");
const sec = (ms: number | null) => (ms === null ? "—" : (ms / 1000).toFixed(1));

export function buildResultsBlock() {
  const trajectory = readOptimizationTrajectory(ITERATIONS);
  if (!trajectory) return `${START}\n_No official iterations yet._\n${END}`;
  const names = readdirSync(ITERATIONS).filter((name) => /^iteration-\d{3}$/.test(name)).sort();
  const categoriesSeen = new Set<string>();
  const rows = names.map((name) => {
    const manifest = readJson<Record<string, any>>(join(ITERATIONS, name, "manifest.json"));
    const benchmark = readJson<Record<string, any>>(join(ITERATIONS, name, "benchmark.json"));
    const metric = benchmark.configurations[manifest.configuration] as Metric;
    const attempt = trajectory.attempts.find((entry) => entry.iteration === name);
    const categories = Object.fromEntries(
      Object.entries(benchmark.categories as Record<string, Record<string, Metric>>).map(([category, value]) => {
        categoriesSeen.add(category);
        const m = value[manifest.configuration]!;
        return [category, `${m.passed}/${m.runs}`];
      }),
    );
    return { name, manifest, metric, decision: attempt?.decision ?? "—", categories };
  });
  const categoryOrder = ["sulekh", "rangoli", "shatranj", "family", "interface"].filter((category) =>
    categoriesSeen.has(category),
  );
  const lines = [
    START,
    "",
    "Generated by `pnpm eval:results` from `evals/iterations/*/manifest.json` and `benchmark.json`. Do not edit by hand.",
    "",
    "| Iteration | Condition | Decision | Task success | Critical | First-pass valid | Tokens/try | s/try | Failed calls | Retries | " +
      categoryOrder.join(" | ") +
      " |",
    "|---|---|---|---:|---:|---:|---:|---:|---:|---:|" + categoryOrder.map(() => "---:").join("|") + "|",
    ...rows.map(
      ({ name, manifest, metric, decision, categories }) =>
        `| #${name.replace("iteration-", "")} | ${manifest.configuration} | ${decision} | ${metric.passed}/${metric.runs} (${pct(
          metric.passRate,
        )}) | ${pct(metric.criticalPassRate)} | ${pct(metric.firstPassValidRate)} | ${int(metric.meanTokensPerRun)} | ${sec(
          metric.meanWallTimeMs,
        )} | ${metric.failedToolCalls} | ${metric.retries} | ${categoryOrder.map((category) => categories[category] ?? "—").join(" | ")} |`,
    ),
    "",
    `Model \`${rows[0]?.manifest.model}\`, ${rows[0]?.manifest.caseCount} frozen cases × ${rows[0]?.manifest.repetitions} repetitions per iteration, ${
      (rows[0]?.manifest.caseTimeoutMs ?? 0) / 1000
    } s per case. Tokens/try counts every input token (uncached, cache-write and cache-read) plus output tokens. The acceptance gate is computed in \`evals/runner/trajectory.ts\`.`,
    "",
    "![Optimization trajectory](evals/optimization/trajectory.svg)",
    "",
    END,
  ];
  return lines.join("\n");
}

function main() {
  const block = buildResultsBlock();
  const check = process.argv.includes("--check");
  const current = existsSync(DOC) ? readFileSync(DOC, "utf8") : "";
  if (!current.includes(START) || !current.includes(END)) {
    throw new Error(`EVALUATION.md is missing the ${START} / ${END} markers.`);
  }
  const next = current.replace(new RegExp(`${START}[\\s\\S]*?${END}`), block);
  if (check) {
    const bundle = buildOptimizationTrajectory(ITERATIONS);
    const trajectoryCurrent =
      !bundle ||
      (readFileSync(join(ROOT, "evals/optimization/trajectory.json"), "utf8") === bundle.json &&
        readFileSync(join(ROOT, "evals/optimization/trajectory.svg"), "utf8") === bundle.svg);
    if (next !== current || !trajectoryCurrent) {
      process.stderr.write("Results block or trajectory is out of date. Run pnpm eval:results.\n");
      process.exitCode = 1;
    }
    return;
  }
  writeOptimizationTrajectory(ITERATIONS, join(ROOT, "evals/optimization"));
  writeFileSync(DOC, next);
  process.stdout.write("EVALUATION.md results block and trajectory updated.\n");
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) main();
